/**
 * Scans public/works and writes src/lib/works.generated.ts.
 * Run via: npm run generate:works
 * Hooked to predev and prebuild — runs automatically before each dev/build.
 */

import { readdir, writeFile } from "fs/promises";
import { join, extname, basename } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const WORKS_DIR = join(__dirname, "../public/works");
const OUTPUT    = join(__dirname, "../src/lib/works.generated.ts");

const SUPPORTED = new Set([".webp", ".jpg", ".jpeg", ".png", ".avif"]);

/** Convert filename to readable title */
function toTitle(filename) {
  const stem = basename(filename, extname(filename));
  // Hash-like names (32+ hex chars) → use first 8 chars uppercased
  if (/^[0-9a-f]{20,}$/i.test(stem)) return stem.slice(0, 8).toUpperCase();
  return stem
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Infer category from filename keywords */
function toCategory(filename) {
  const lc = filename.toLowerCase();
  if (/screenshot|screen|website|web|site|page|ui|interface|app/.test(lc)) return "Website Screenshot";
  if (/portrait|face|person|model|editorial|beauty/.test(lc)) return "Portrait Study";
  if (/cover|magazine|editorial/.test(lc)) return "Editorial Cover";
  if (/logo|brand|identity/.test(lc)) return "Brand Identity";
  return "Visual Direction Study";
}

/** Coarse aspect-ratio classification from filename */
function toAr(filename) {
  const lc = filename.toLowerCase();
  if (/wide|landscape|banner|car|hero|horizontal|screen|screenshot|website/.test(lc)) return "wide";
  if (/square/.test(lc)) return "square";
  return "portrait"; // default
}

async function main() {
  let files;
  try {
    files = await readdir(WORKS_DIR);
  } catch {
    console.warn("[generate-works] public/works not found — writing empty manifest.");
    files = [];
  }

  const images = files
    .filter((f) => !f.startsWith(".") && SUPPORTED.has(extname(f).toLowerCase()))
    .sort();

  const items = images.map((f) => ({
    src:      `/works/${f}`,
    title:    toTitle(f),
    category: toCategory(f),
    ar:       toAr(f),
  }));

  const ts = `// AUTO-GENERATED by scripts/generate-works-manifest.mjs
// Do NOT edit manually. Run \`npm run generate:works\` to refresh,
// or just run \`npm run dev\` / \`npm run build\` — it runs automatically.

export type GeneratedWork = {
  src: string;
  title: string;
  category: string;
  /** "portrait" | "wide" | "square" */
  ar: string;
};

export const generatedWorks: GeneratedWork[] = ${JSON.stringify(items, null, 2)};
`;

  await writeFile(OUTPUT, ts, "utf8");
  console.log(`[generate-works] ${items.length} works → src/lib/works.generated.ts`);
}

main().catch((err) => { console.error(err); process.exit(1); });
